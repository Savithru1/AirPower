"""Write docs/THIRD_PARTY.md: the licence of every Python package in requirements.txt, every npm package
shipped in the dashboard, and the terms of every dataset in data/manifest.json. Read from the installed
package metadata, the npm lock file and the manifest; nothing is typed by hand.

    python -m tools.licences
"""
import json
import re
import sys
from datetime import date
from importlib import metadata

from airpower.config import MANIFEST, ROOT

EXTRA = ["progpy", "filterpy"]            # installed without dependencies (README)


def py_license(dist):
    m = dist.metadata
    expr = m.get("License-Expression")
    if expr:
        return expr
    lic = (m.get("License") or "").strip()
    if lic and len(lic) < 80 and "\n" not in lic:
        return lic
    cls = [c.split("::")[-1].strip() for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
    return "; ".join(cls) or (lic.splitlines()[0][:80] if lic else "not declared in the package metadata")


def requirement_names():
    out = []
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if line:
            out.append(re.split(r"[<>=\[ ;]", line)[0])
    return out + EXTRA


def main():
    L = ["# Third-party software and data", "",
         f"Generated by `tools/licences.py` on {date.today().isoformat()}. Python packages: installed metadata of the packages named in "
         "`requirements.txt` (direct dependencies; their own dependencies carry their own licences). npm: `web/package-lock.json`, the "
         "packages bundled into the dashboard. Datasets: `data/manifest.json`. Nothing here is legal advice; confirm with the unit's "
         "legal adviser before any release outside the project.", "",
         "## Python", "", "| Package | Version | Licence |", "|---|---|---|"]
    seen = set()
    for n in requirement_names():
        try:
            d = metadata.distribution(n)
        except metadata.PackageNotFoundError:
            L.append(f"| {n} | not installed | - |")
            continue
        key = d.metadata["Name"].lower()
        if key in seen:
            continue
        seen.add(key)
        L.append(f"| {d.metadata['Name']} | {d.version} | {py_license(d)} |")
    lock = json.loads((ROOT / "web" / "package-lock.json").read_text(encoding="utf-8"))
    direct = set(lock["packages"][""].get("dependencies", {}))
    rows, lic_count = [], {}
    for path, p in lock["packages"].items():
        if not path or p.get("dev"):
            continue
        name = path.split("node_modules/")[-1]
        lic_count[p.get("license", "not declared")] = lic_count.get(p.get("license", "not declared"), 0) + 1
        rows.append((name in direct, name, p.get("version"), p.get("license", "not declared")))
    L += ["", "## npm (bundled into the dashboard)", "",
          f"{len(rows)} packages (runtime, not build tools). Licences: " + ", ".join(f"{k} x {v}" for k, v in sorted(lic_count.items(), key=lambda kv: -kv[1])) + ".",
          "", "| Package | Version | Licence | Direct |", "|---|---|---|---|"]
    for direct_, name, ver, lic in sorted(rows, key=lambda r: (not r[0], r[1])):
        if direct_ or lic not in ("MIT", "Apache-2.0", "ISC", "BSD-3-Clause", "BSD-2-Clause"):
            L.append(f"| {name} | {ver} | {lic} | {'yes' if direct_ else ''} |")
    L += ["", "Packages under MIT, Apache-2.0, ISC or BSD licences that are not direct dependencies are counted above, not listed.",
          "", "## Datasets", "", "| Dataset | Used for | Terms | Status |", "|---|---|---|---|"]
    man = json.loads(MANIFEST.read_text(encoding="utf-8"))
    for s in man["sources"]:
        L.append(f"| {s['title']} | {s['covers']} | {s['licence']} | {s['status']} |")
    L += ["", "Datasets are read in place or downloaded by `tools/fetch_real_data.py`; none is redistributed in this repository "
          "(`data/raw` and `data/processed` are git-ignored).", ""]
    out = ROOT / "docs" / "THIRD_PARTY.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"-> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
